import assert from 'node:assert/strict';
import fs from 'node:fs';

// node scripts/build_pokemon_null_126_lua.mjs /path/to/null126.gba
const romPath = process.argv[2];
assert(romPath, 'Provide the Pokemon Null 1.2.6 ROM');
const rom = fs.readFileSync(romPath);
assert.equal(rom.readUInt32LE(0x89034), 0x083E3F50, 'Unexpected EXP table pointer');
assert.equal(rom.readUInt32LE(0x89038), 0x083E4BF0, 'Unexpected species table pointer');

const luaDir = new URL('../lua/', import.meta.url);
let lua = fs.readFileSync(new URL('pokemonnull1.2.5.lua', luaDir), 'utf8');
function replace(pattern, replacement) {
    assert(pattern.test(lua), `Missing Lua anchor: ${pattern}`);
    lua = lua.replace(pattern, replacement);
}

replace(/^-- Generated by [^\n]+/, '-- Generated by scripts/build_pokemon_null_126_lua.mjs from the 1.2.5 sync bundle.');
replace(/local speciesInfo=0x[\da-f]+/i, 'local speciesInfo=0x083E4BF0');
replace(/local speciesNameTable=0x[\da-f]+/i, 'local speciesNameTable=0x083CB3A8');
replace(/__VSRECORDER_POKEMON_NULL_125_MAP__/, '__VSRECORDER_POKEMON_NULL_126_MAP__');
replace(/pokemonnull125\.map/g, 'pokemonnull126.map');

replace(/local function getPokemonNullRomTables\(\)[\s\S]*?\nend/, [
    'local function getPokemonNullRomTables()',
    '\t-- Check the literal pool in the 1.2.6 ROM before decoding any levels.',
    '\tlocal expTable = emu:read32(0x08089034)',
    '\tassert(expTable == 0x083E3F50 and emu:read32(0x08089038) == speciesInfo,',
    '\t\t"pokemonnull1.2.6.lua requires the Pokemon Null 1.2.6 ROM")',
    '\treturn speciesInfo, expTable',
    'end',
].join('\n'));
replace(/(function buildPackedBoxBytes\(\)\n)/, '$1\tgetPokemonNullRomTables()\n');

fs.writeFileSync(new URL('pokemonnull1.2.6.lua', luaDir), lua);
