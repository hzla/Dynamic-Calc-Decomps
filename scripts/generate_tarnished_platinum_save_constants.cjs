const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const { extend } = require("../calc/util");

const [constantsDir] = process.argv.slice(2);
if (!constantsDir) {
    throw new Error("Usage: node scripts/generate_tarnished_platinum_save_constants.cjs <constants directory>");
}

const root = path.resolve(__dirname, "..");
const ctx = vm.createContext({ window: {}, calc: { extend } });
for (const file of ["calc/data/vanilla/base-game-data.js", "js/savereaders/enums.js"]) {
    vm.runInContext(fs.readFileSync(path.join(root, file), "utf8"), ctx);
}
const vanilla = ctx.window.calcVanillaData;
const toId = value => value.toLowerCase().replace(/[^a-z0-9]/g, "");
const indexNames = names => new Map(names.filter(Boolean).map(name => [toId(name), name]));

function readIds(file, prefix, terminator) {
    const rows = fs.readFileSync(path.join(constantsDir, file + ".txt"), "utf8").trimEnd().split(/\r?\n/);
    if (terminator) assert.equal(rows.pop().trim(), terminator);
    return rows.map((row, id) => {
        const token = row.trim();
        assert.match(token, new RegExp(`^${prefix}[A-Z0-9_]+$`), `${file}.txt ID ${id}: ${token}`);
        return token.slice(prefix.length);
    });
}

const speciesIds = readIds("species", "SPECIES_");
const speciesNames = indexNames(Object.keys(vanilla.species[9]));
const speciesAliases = {
    NONE: "", EGG: "Egg", BAD_EGG: "Bad Egg",
    OINKOLOGNE_M: "Oinkologne", MEOWSTIC_M: "Meowstic",
    MEGA_GARDEVOIR: "Gardevoir-Mega", BASCULEGION_FEMALE: "Basculegion-F",
    LUCARIO_M: "Lucario", LUCARIO_F: "Lucario",
    TAUROS_BLAZE: "Tauros-Paldea-Blaze", TAUROS_AQUA: "Tauros-Paldea-Aqua",
    SAWSBUCK_WINTER: "Sawsbuck-Winter", PIKACHU_BELLE: "Pikachu-Belle",
    PIKACHU_ROCK_STAR: "Pikachu-Rock-Star", PIKACHU_POP_STAR: "Pikachu-Pop-Star", PIKACHU_LIBRE: "Pikachu-Libre",
};
const normalizeRegion = key => key.replace(/_ALOLAN$/, "_ALOLA").replace(/_GALARIAN$/, "_GALAR").replace(/_HISUIAN$/, "_HISUI");
const poks = speciesIds.map(key => speciesAliases[key] ?? speciesNames.get(toId(normalizeRegion(key))));

const moveNames = indexNames(Object.keys(vanilla.moves[9]));
const moveAliases = {
    NONE: "-----", VICE_GRIP: "Vise Grip", HI_JUMP_KICK: "High Jump Kick",
    FAINT_ATTACK: "Feint Attack", SMELLING_SALT: "Smelling Salts", "1ST_IMPRESSION": "First Impression",
    HI_HORSEPOWER: "High Horsepower", STOMP_TANTRUM: "Stomping Tantrum", TRIPLE_ARROW: "Triple Arrows",
};
const moves = readIds("moves", "MOVE_", "MAX_MOVES").map(key => moveAliases[key] ?? moveNames.get(toId(key)));
assert.ok(moves.slice(1).every(name => Object.hasOwn(vanilla.moves[9], name)), "Unrecognized move constant");

const itemNames = indexNames([...ctx.sav_item_names, ...require("../calc/data/items").ITEMS[9]]);
const itemAliases = { X_DEFENSE: "X Defend", DEXNAV: "DexNav" };
const label = key => /^(TM|HM)\d+$/.test(key) ? key : key.toLowerCase().replaceAll("_", " ").replace(/\b\w/g, char => char.toUpperCase());
const items = readIds("items", "ITEM_", "MAX_ITEMS").map(key => itemAliases[key] ?? itemNames.get(toId(key)) ?? label(key));
const abilityNames = indexNames([...ctx.sav_abilities, ...require("../calc/data/abilities").ABILITIES[9]]);
const abilities = readIds("abilities", "ABILITY_").map(key => abilityNames.get(toId(key)) ?? label(key));

const growthIds = new Map(["Medium Fast", "Erratic", "Fluctuating", "Medium Slow", "Fast", "Slow"]
    .map((label, id) => [label, id]));
const growthRows = fs.readFileSync(path.join(constantsDir, "growth_rates.txt"), "utf8").trimEnd().split(/\r?\n/);
assert.equal(growthRows.length, speciesIds.length, "Expected one growth rate for each species ID");
const growths = growthRows.map((row, id) => {
    const fields = row.split("\t").map(value => value.trim());
    assert.equal(fields.length, 3, `Expected ID, species constant, and growth rate on growth_rates.txt line ${id + 1}`);
    const [saveId, species, rate] = fields;
    assert.equal(saveId, String(id), `Unexpected growth rate ID for ${species}`);
    assert.equal(species, `SPECIES_${speciesIds[id]}`, `Growth rate species mismatch at ID ${id}`);
    assert.notEqual(poks[id], undefined, `Unrecognized species ID ${id}: ${species}`);
    assert.ok(growthIds.has(rate), `Unknown growth rate for ${species}: ${rate}`);
    return growthIds.get(rate);
});

const tables = { poks, moves, items, growths, abilities };
const formatRows = values => Array.from({ length: Math.ceil(values.length / 10) }, (_, row) =>
    "        " + values.slice(row * 10, row * 10 + 10).map(value => JSON.stringify(value)).join(", ") + ",").join("\n");
const output = "// Generated by scripts/generate_tarnished_platinum_save_constants.cjs. Array indices are ROM IDs.\n" +
    "window.TARNISHED_PLATINUM_SAVE_INCLUDES = {\n" +
    Object.entries(tables).map(([key, values]) => `    ${key}: [\n${formatRows(values)}\n    ],\n`).join("") +
    "};\n";
fs.writeFileSync(path.join(root, "js/savereaders/save_constants/tarnished_platinum.js"), output);
